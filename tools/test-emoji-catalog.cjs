const assert = require('node:assert/strict'), fs = require('node:fs'), vm = require('node:vm');
const ts = require('/Applications/DevEco-Studio.app/Contents/sdk/default/openharmony/ets/build-tools/ets-loader/node_modules/typescript/lib/typescript.js');
const api = {};
vm.runInNewContext(ts.transpileModule(fs.readFileSync('entry/src/main/ets/input/EmojiCatalog.ets', 'utf8'), {compilerOptions: {module: ts.ModuleKind.CommonJS}}).outputText, {exports: api});
